import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { canonicalJsonV3 } from "../src/core/events/v3/canonical.ts";
import { EVENT_V3_CORE_EVENT_TYPES, EventV3Schema } from "../src/core/events/v3/contract.ts";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = resolve(repositoryRoot, "schemas/event-v3.schema.json");
const generatedPath = resolve(repositoryRoot, "src/core/events/v3/generated.ts");
const lineagePath = resolve(repositoryRoot, "schemas/event-v3-lineage.json");
const digest = `sha256:${createHash("sha256")
  .update(canonicalJsonV3(EventV3Schema))
  .digest("hex")}`;
const schemaBody = `${JSON.stringify(EventV3Schema, null, 2)}\n`;
const generatedTypes = EVENT_V3_CORE_EVENT_TYPES.map(
  (eventType) => `  ${JSON.stringify(eventType)},`,
).join("\n");
const lineageGroups = readLineageGroups(lineagePath);
const generatedLineage = lineageGroups.map(formatLineageGroup).join("\n");
const generatedBody = `/** Generated by scripts/generate-event-v3-contract.ts. Do not edit. */\nexport const EVENT_V3_SCHEMA_DIGEST =\n  ${JSON.stringify(digest)} as const;\nexport const EVENT_V3_GENERATED_CORE_TYPES = [\n${generatedTypes}\n] as const;\n/** Committed schema history: additive groups, oldest first (schemas/event-v3-lineage.json). */\nexport const EVENT_V3_SCHEMA_LINEAGE = {\n  groups: [\n${generatedLineage}\n  ],\n} as const;\n`;

const outputs = [
  [schemaPath, schemaBody],
  [generatedPath, generatedBody],
] as const;

if (process.argv.includes("--check")) {
  const drifted = outputs.filter(
    ([path, expected]) => !existsSync(path) || readFileSync(path, "utf8") !== expected,
  );
  if (drifted.length > 0) {
    for (const [path] of drifted) console.error(`generated V3 contract drift: ${path}`);
    process.exitCode = 1;
  }
} else {
  for (const [path, body] of outputs) writeFileSync(path, body, "utf8");
  console.log(`generated ${schemaPath}`);
  console.log(`schema digest ${digest}`);
}

function readLineageGroups(path: string): string[][] {
  const lineage = JSON.parse(readFileSync(path, "utf8")) as {
    format?: unknown;
    format_version?: unknown;
    groups?: unknown;
  };
  if (lineage.format !== "harnery-event-v3-schema-lineage" || lineage.format_version !== 1) {
    throw new Error(`unsupported V3 schema lineage format: ${path}`);
  }
  const groups = lineage.groups;
  if (
    !Array.isArray(groups) ||
    groups.length === 0 ||
    !groups.every(
      (group) =>
        Array.isArray(group) &&
        group.length > 0 &&
        group.every((entry) => typeof entry === "string" && /^sha256:[0-9a-f]{64}$/.test(entry)),
    )
  ) {
    throw new Error(`invalid V3 schema lineage groups: ${path}`);
  }
  return groups as string[][];
}

function formatLineageGroup(group: readonly string[]): string {
  const inline = `    [${group.map((entry) => JSON.stringify(entry)).join(", ")}],`;
  if (inline.length <= 100) return inline;
  return `    [\n${group.map((entry) => `      ${JSON.stringify(entry)},`).join("\n")}\n    ],`;
}
