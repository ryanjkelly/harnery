#!/usr/bin/env bun
/**
 * Generate `claude-code-plugin/hooks/generated/harnery.js`, the one module the
 * Claude Code plugin imports from Harnery's own source.
 *
 * A Claude Code hooks module may import only relative paths, so the plugin
 * cannot reach `src/`. This script copies what it needs into a plain ES module:
 * the helper-limit decision (`src/core/helper-limit.ts`, which imports nothing),
 * the Claude Code rankings from the adapter profile, the minimum Claude Code
 * version, and the JSONC comment stripper the config reader uses. The plugin and
 * the rest of Harnery therefore share one decision function.
 *
 * The output is committed so a source checkout works without a build step.
 * `--check` exits 1 when the committed file differs from what this script would
 * write; a unit test runs the same comparison.
 *
 *   bun run scripts/build-claude-code-plugin.ts           write the module
 *   bun run scripts/build-claude-code-plugin.ts --check   fail when it is stale
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { BUILTIN_ADAPTER_PROFILES } from "../src/core/adapters/profiles.ts";
import { stripJsonComments } from "../src/core/config.ts";
import { helperLadders } from "../src/core/helper-limit.ts";
import { HELPER_PLUGIN_MIN_CLAUDE_VERSION } from "../src/core/helper-plugin.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

/** Where the generated module lives, relative to the package root. */
export const GENERATED_PLUGIN_MODULE = "claude-code-plugin/hooks/generated/harnery.js";

/** The text the generated module should hold for the current source. */
export function renderClaudeCodePluginModule(): string {
  const source = readFileSync(join(root, "src/core/helper-limit.ts"), "utf8");
  const transpiler = new Bun.Transpiler({ loader: "ts", target: "browser" });
  const decision = transpiler.transformSync(source).trim();
  if (/^\s*import\s/m.test(decision) || /\brequire\(/.test(decision)) {
    throw new Error("src/core/helper-limit.ts must import nothing to be bundled into the plugin");
  }
  const ladders = helperLadders(BUILTIN_ADAPTER_PROFILES["claude-code"]);
  const stripper = stripJsonComments.toString().trim();
  return [
    "// Generated by scripts/build-claude-code-plugin.ts from Harnery's source.",
    "// Do not edit; run `bun run build:claude-code-plugin` after changing the source.",
    "",
    "// src/core/helper-limit.ts",
    decision,
    "",
    "// Claude Code rankings from src/core/adapters/profiles.ts.",
    `export const CLAUDE_CODE_LADDERS = ${JSON.stringify(ladders)};`,
    "",
    "// HELPER_PLUGIN_MIN_CLAUDE_VERSION from src/core/helper-plugin.ts.",
    `export const MIN_CLAUDE_VERSION = ${JSON.stringify(HELPER_PLUGIN_MIN_CLAUDE_VERSION)};`,
    "",
    "// stripJsonComments from src/core/config.ts.",
    `export ${stripper}`,
    "",
  ].join("\n");
}

if (import.meta.main) {
  const target = join(root, GENERATED_PLUGIN_MODULE);
  const next = renderClaudeCodePluginModule();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(target, "utf8");
    } catch {
      // A missing file is stale.
    }
    if (current !== next) {
      console.error(
        `${GENERATED_PLUGIN_MODULE} is stale; run \`bun run build:claude-code-plugin\`.`,
      );
      process.exit(1);
    }
    console.log(`${GENERATED_PLUGIN_MODULE} is current.`);
  } else {
    writeFileSync(target, next);
    console.log(`Wrote ${GENERATED_PLUGIN_MODULE}.`);
  }
}
